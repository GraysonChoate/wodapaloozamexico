from PIL import Image, ImageDraw
import glob, os, sys
D = sys.argv[1]
for tag, tw, cols in (("desktop-1440x900", 250, 10), ("mobile-375x812", 110, 13)):
    fs = sorted(glob.glob(f"{D}/{tag}_*.jpg"))
    if not fs: continue
    ims = [(os.path.basename(f).split("_",1)[1][:-4], Image.open(f)) for f in fs]
    th = int(ims[0][1].height * tw / ims[0][1].width); rows = (len(ims)+cols-1)//cols
    s = Image.new("RGB", (cols*tw+(cols+1)*5, rows*(th+13)+(rows+1)*5), (18,18,18))
    d = ImageDraw.Draw(s)
    for i,(name,im) in enumerate(ims):
        x = 5+(i%cols)*(tw+5); y = 5+(i//cols)*(th+13+5)
        s.paste(im.resize((tw,th)), (x,y)); d.text((x+2, y+th+1), name[:28], fill=(255,215,90))
    s.save(f"{D}/CONTACT-{tag}.jpg", quality=80)
    print(f"  CONTACT-{tag}.jpg  {len(ims)} frames")
PY

write_index "$DIR" "$SHA"
echo "  audit set: $DIR"
