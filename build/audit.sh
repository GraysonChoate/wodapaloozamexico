# pointing at the wrong pictures. An index that misdescribes the evidence is worse than no
# index, because it is read as authoritative.
#
# STOPS below is the single source of truth: the capture and the table are generated from
# it, so they cannot disagree.
#
#   ./audit.sh [url]              capture + index into audit/<short-sha>/
#   ./audit.sh --index-only DIR   rewrite one folder's AUDIT.md from the frames it holds

