write_index () {
  local DIR="$1" SHA="$2"
  {
    printf '# VISUAL AUDIT — `%s`\n\n' "$SHA"
    cat <<'HEAD'
Frames from the pushed commit, captured in **headed Chromium** — a real browser window with a
real compositor. The UA was checked for a `Headless` marker before capture and carried none.
Nothing here comes from the embedded preview pane, which in this setup never fires scroll
events and never starts media playback.

**This file is generated by `build/audit.sh` from the same stop list that drove the capture**,
so the table cannot drift from the pictures. It previously was not, and three indexes ended up
describing eighteen stops for sets of sixty to eighty frames.

Two loops of the wide `SUCEDERÁ` state live one level up as `audit/sucedera-wide-BEFORE.gif`
and `-AFTER.gif`. A still cannot approve that state; those can.

Start here:

    CONTACT-desktop-1440x900.jpg     every stop, desktop
    CONTACT-mobile-375x812.jpg       every stop, mobile

Individual frames are `<viewport>_<nn>-<name>.jpg`. Stops are a fraction through a *named
beat*, not through the document, so they stay meaningful as the film grows.

| # | stop | what to look at |
|---|---|---|
HEAD
    # Drive the table from the FILES THAT EXIST, not from the stop list. A historical set
    # was captured with the stop names of its own day, and describing it with today's list
    # silently drops most of its frames — which is the same failure as before, in a new
    # costume. Unknown names still get a row; they just have no curated note.
    for f in "$DIR"/desktop-*_*.jpg; do
      [ -e "$f" ] || continue
      base="$(basename "$f")"; name="${base#*_}"; name="${name%.jpg}"
      row="$(grep -m1 "^${name}|" <<< "$STOPS" || true)"
      if [ -n "$row" ]; then
        IFS='|' read -r _ beat frac note <<< "$row"
        printf '| %s | %s · %s | %s |\n' "${name%%-*}" "$beat" "$frac" "$note"
      else
        printf '| %s | %s | — (stop from an earlier milestone; name predates the current list) |\n' \
          "${name%%-*}" "${name#*-}"
      fi
    done
    cat <<'TAIL'

## Known limits of these stills

- **They cannot show motion.** Beat 5's panels loop at uneven rates (0.78×–1.18×) so the nine
  breathe out of sync; a still shows nine frozen figures. Same for the banner breathing in
  Beat 6 and the wind throughout.
- **They cannot show the transitions.** Every beat boundary is a dip to black, and stops sit
  inside beats rather than across seams.
- **Beat 7's metadata line moves sideways** while the page moves down. A still shows it
  parked. It is the only cross-axis motion in the film, and it is interface, never footage.
- **Beat 8 is the stillness beat and stills flatter it.** Its final 40% of scroll is a
  near-static hold; a contact sheet cannot show that the reader spent two screens there.
- **Mobile Beat 6 has no vertical travel** — the 1080×1920 source fits a portrait viewport by
  height. That is the material, not a regression.
- **The film's own watermark is visible in the bright beats.** `WZA_MX_LOGO.mp4` burns a
  `WODAPALOOZA MEXICO CITY` lockup at bottom-right in every frame at identical size. It is in
  Beats 1, 2 and 4 too, invisible only because those frames are dark. Open for review.

Regenerate with `build/audit.sh`.
TAIL
  } > "$DIR/AUDIT.md"
  echo "  wrote $DIR/AUDIT.md ($(grep -c '^| [0-9]' "$DIR/AUDIT.md") stops)"
}

if [ "${1:-}" = "--index-only" ]; then
  D="${2:?usage: audit.sh --index-only <dir>}"
  write_index "$D" "$(basename "$D")"
  exit 0
fi

PAGE="${1:-http://localhost:4173/index.html}"
SHA="$(cd "$REPO" && git rev-parse --short HEAD)"
DIR="$REPO/audit/$SHA"
mkdir -p "$DIR"
CH="$(ls -d "$HOME"/Library/Caches/ms-playwright/chromium-*/chrome-mac*/*.app/Contents/MacOS/* 2>/dev/null | head -1)"
[ -x "$CH" ] || { echo "  no chromium binary"; exit 2; }

printf '%s\n' "$STOPS" | awk -F'|' 'NF>2{print $1"|"$2"|"$3}' > "$DIR/.stops"

NODE_PATH="$HOME/.gl-rig/node_modules" node -e '
const {chromium} = require("playwright-core");
const fs = require("fs");
const [CH, PAGE, DIR] = process.argv.slice(1);
const S = fs.readFileSync(DIR + "/.stops", "utf8").trim().split("\n")
  .map(l => l.split("|")).map(([name, beat, frac]) => [beat, Number(frac), name]);
(async () => {
  const br = await chromium.launch({executablePath: CH, headless: false,
                                    args:["--autoplay-policy=no-user-gesture-required"]});
  const ua = await (async () => { const p = await br.newPage();
    const u = await p.evaluate(() => navigator.userAgent); await p.close(); return u; })();
  if (/Headless/.test(ua)) { console.log("  HEADLESS — this set is not valid"); process.exit(1); }
  console.log("  headed Chromium, real window");
  for (const [tag, w, h] of [["desktop-1440x900",1440,900],["mobile-375x812",375,812]]) {
    const p = await br.newPage({viewport:{width:w, height:h}});
    await p.goto(PAGE); await p.waitForTimeout(3800);
    for (const [id, f, name] of S) {
      const box = await p.evaluate(i => { const e = document.getElementById(i);
        return e ? {top: e.offsetTop, tr: Math.max(1, e.offsetHeight - innerHeight)} : null; }, id);
      if (!box) continue;
      await p.evaluate(a => window.scrollTo(0, Math.round(a.top + a.tr * a.f)), {...box, f});
      await p.waitForTimeout(800);
      await p.screenshot({path: `${DIR}/${tag}_${name}.jpg`, type:"jpeg", quality:72});
    }
    await p.close(); console.log("  captured " + tag);
  }
  await br.close();
})();
' "$CH" "$PAGE" "$DIR" || exit 1
rm -f "$DIR/.stops"

